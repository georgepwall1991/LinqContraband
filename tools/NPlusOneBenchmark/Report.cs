using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using NPlusOneBenchmark.Corpus;

namespace NPlusOneBenchmark;

/// <summary>Renders the committed results file. The output is deterministic so it can be diffed in review.</summary>
internal static class Report
{
    public const string WriteCommand = "dotnet run --project tools/NPlusOneBenchmark/NPlusOneBenchmark.csproj -- --write";

    public static string Render(IReadOnlyList<CaseResult> results)
    {
        var positives = results.Where(result => result.Measurement.IsNPlusOne).ToArray();
        var negatives = results.Where(result => !result.Measurement.IsNPlusOne).ToArray();
        var builder = new StringBuilder();

        builder.AppendLine("# N+1 benchmark results");
        builder.AppendLine();
        builder.AppendLine($"Generated by `{WriteCommand}`. Do not edit by hand; CI fails when this file is out of date.");
        builder.AppendLine();
        builder.AppendLine(
            $"Every case ran against SQLite with {CaseRunner.SmallSize} and then {CaseRunner.LargeSize} customers. " +
            "A case is a proven N+1 when the larger database cost it more round trips, and proven safe when the count stayed the same. A round trip is one SQL command, or one `SaveChanges` call however many rows it writes. " +
            $"A case counts as reported when {string.Join(", ", CorpusAnalysis.NPlusOneRuleIds.OrderBy(id => id, StringComparer.Ordinal))} " +
            "fires anywhere inside it with the package's default configuration.");
        builder.AppendLine();

        builder.AppendLine("## Summary");
        builder.AppendLine();
        builder.AppendLine("| Measure | Cases | Reported | Rate |");
        builder.AppendLine("| --- | ---: | ---: | ---: |");
        builder.AppendLine($"| Recall on proven N+1 cases | {positives.Length} | {positives.Count(result => result.Reported)} | {Percent(positives)} |");
        builder.AppendLine($"| False positives on proven safe cases | {negatives.Length} | {negatives.Count(result => result.Reported)} | {Percent(negatives)} |");
        builder.AppendLine();

        builder.AppendLine("## Recall by kind");
        builder.AppendLine();
        AppendBreakdown(builder, "Kind", positives, result => result.Case.Kind.ToString(), Enum.GetNames<Kind>());

        builder.AppendLine("## Recall by how the database call is reached");
        builder.AppendLine();
        AppendBreakdown(builder, "Reached through", positives, result => result.Case.Via.ToString(), Enum.GetNames<Via>());

        builder.AppendLine("## False positives");
        builder.AppendLine();
        AppendCaseList(builder, negatives.Where(result => result.Reported), "None.");

        builder.AppendLine("## Missed N+1 cases");
        builder.AppendLine();
        AppendCaseList(builder, positives.Where(result => !result.Reported), "None.");

        builder.AppendLine("## Every case");
        builder.AppendLine();
        builder.AppendLine($"| Case | Kind | Reached through | Round trips ({CaseRunner.SmallSize} → {CaseRunner.LargeSize}) | Proven | Reported |");
        builder.AppendLine("| --- | --- | --- | ---: | --- | --- |");
        foreach (var result in results)
        {
            builder.AppendLine(
                $"| {result.Case.Name} | {result.Case.Kind} | {result.Case.Via} | " +
                $"{result.Measurement.SmallCount} → {result.Measurement.LargeCount} | " +
                $"{(result.Measurement.IsNPlusOne ? "N+1" : "safe")} | {(result.Reported ? string.Join(", ", result.ReportedRules) : "")} |");
        }

        return builder.ToString();
    }

    public static string Summarize(IReadOnlyList<CaseResult> results)
    {
        var positives = results.Where(result => result.Measurement.IsNPlusOne).ToArray();
        var negatives = results.Where(result => !result.Measurement.IsNPlusOne).ToArray();
        return
            $"Recall: {positives.Count(result => result.Reported)} of {positives.Length} proven N+1 cases ({Percent(positives)}). " +
            $"False positives: {negatives.Count(result => result.Reported)} of {negatives.Length} proven safe cases ({Percent(negatives)}).";
    }

    private static void AppendBreakdown(
        StringBuilder builder, string heading, CaseResult[] positives, Func<CaseResult, string> key, string[] order)
    {
        builder.AppendLine($"| {heading} | Proven N+1 | Reported | Recall |");
        builder.AppendLine("| --- | ---: | ---: | ---: |");
        foreach (var name in order)
        {
            var group = positives.Where(result => key(result) == name).ToArray();
            if (group.Length > 0)
                builder.AppendLine($"| {name} | {group.Length} | {group.Count(result => result.Reported)} | {Percent(group)} |");
        }

        builder.AppendLine();
    }

    private static void AppendCaseList(StringBuilder builder, IEnumerable<CaseResult> results, string whenEmpty)
    {
        var any = false;
        foreach (var result in results)
        {
            any = true;
            var rules = result.Reported ? $": {string.Join(", ", result.ReportedRules)}" : "";
            builder.AppendLine($"- {result.Case.Name} ({result.Case.Kind}, {result.Case.Via}){rules}");
        }

        if (!any)
            builder.AppendLine(whenEmpty);

        builder.AppendLine();
    }

    private static string Percent(CaseResult[] results) =>
        results.Length == 0
            ? "n/a"
            : (100.0 * results.Count(result => result.Reported) / results.Length).ToString("0.0", CultureInfo.InvariantCulture) + "%";
}
